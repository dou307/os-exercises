  const reviewed=index.filter(q=>q.id.startsWith('c3-'));
  check('第三章166题都有逐题状态',reviewed.length===166&&reviewed.every(q=>q.status==='reviewed'&&q.review!=='systematic'));
  check('11道第三章争议全部排除计分',reviewed.filter(q=>q.review==='disputed').length===11&&reviewed.filter(q=>q.review==='disputed').every(q=>q.scoring==='excluded'));
  check('230系统映射只来自第四第五章',index.filter(q=>q.review==='systematic').length===230&&index.filter(q=>q.review==='systematic').every(q=>/^c[45]-/.test(q.id)));
  check('第二章审核结果维持276题23争议',index.filter(q=>q.id.startsWith('c2-')).length===276&&index.filter(q=>q.id.startsWith('c2-')&&q.review==='disputed').length===23);
  check('本轮不修改默认已学章',JSON.stringify(await page.evaluate(()=>window.__osExercises.meta.studyDefaults.confirmedCompletedChapters))==='["1"]');
  check('链接问题映射课程2且伙伴映射课程10',index.find(q=>q.id==='c3-s2-0-q010').ch==='2'&&index.find(q=>q.id==='c3-s1-0-q072').ch==='10');
  await go('#/q/c3-s1-0-q007');
  check('作答前审核勘误不提前泄露数值答案',!(await page.locator('.errata').isVisible())&&!(await page.locator('.qcard').innerText()).includes('最小可容纳块应首选'));
  await page.getByRole('button',{name:'查看解析',exact:true}).click();
  check('Best Fit题显示280与合并后410两种前提',(await page.locator('.errata').innerText()).includes('280K')&&(await page.locator('.errata').innerText()).includes('410K'));
  await page.locator('.opt').nth(2).click();await page.getByRole('button',{name:'提交答案',exact:true}).click();
  check('原C选项保留但提交不判对错',(await page.evaluate(()=>window.__osExercises.storage.getAnswer('c3-s1-0-q007'))).correct===null&&await page.locator('.opt.ok,.opt.bad').count()===0);
  await page.screenshot({path:path.join(OUT,ENGINE+'-bestfit.png'),fullPage:true});
  await go('#/q/c3-s2-0-q010');
  await page.getByRole('button',{name:'查看解析',exact:true}).click();
  check('链接勘误保留原C并建议D',(await page.locator('.errata').innerText()).includes('应选D')&&(await page.locator('.qhead').innerText()).includes('待核对'));
  check('勘误有GNU链接器原始资料',await page.locator('.errata a[href="https://man7.org/linux/man-pages/man1/ld.1.html"]').count()===1);
  await go('#/q/c3-s2-0-q013');
  check('普通查看题面时不显示1917等复核结果',!(await page.locator('.qcard').innerText()).includes('1917'));
  await page.getByRole('button',{name:'查看解析',exact:true}).click();

  await page.locator('.opt').nth(2).click();await page.getByRole('button',{name:'提交答案',exact:true}).click();
  check('五次置换与九次缺页正确区分并判C',(await page.evaluate(()=>window.__osExercises.storage.getAnswer('c3-s2-0-q053'))).correct===true);
  await go('#/q/c3-s3-2-q007');
  await page.getByRole('button',{name:'查看解析',exact:true}).click();
  check('严格阈值纠错不是默许95',(await page.locator('.errata').innerText()).includes('h>0.95'));
  await go('#/q/c3-s3-2-q019');
  await page.getByRole('button',{name:'查看解析',exact:true}).click();
  check('缺f1机器码明确标资料不足',(await page.locator('.errata').innerText()).includes('没有函数机器码'));
  await go('#/q/c3-s3-2-q020');
